package com.autoreply.app.core.llm

/**
 * 找话题：按类分好的开场句，输入法面板上点一下直接填进输入框。
 *
 * ## 为什么要有这个
 *
 * 模型能接话，但很多时候卡住的是"没话可说"——对方回了个「嗯」，
 * 或者刚打完招呼不知道下一句问什么。这时候需要的不是"更聪明的模型"，
 * 而是**一个具体的提问**。所以这里放的是可以直接发出去的句子，不是话题标签。
 *
 * ## 为什么是硬编码而不是配置
 *
 * 这些话术属于"通用社交常识"，跟你用哪个人设无关；做成配置项的结果是
 * 大多数人永远不会去填，功能等于不存在。要个性化有「常用短语」那一栏。
 *
 * ## 写这些句子的标准
 *
 * - 一句一个具体问题，不叠加（"你多大做什么工作住哪"没人愿意答）
 * - 不问隐私：收入、体重、家庭矛盾一律不进
 * - 能在对方答完之后自然接下去（"几点睡"→"那早上起得来吗"）
 */
object TopicBank {

    /** 面板上的一行页签，顺序即显示顺序。 */
    val CATS = listOf("日常", "工作", "兴趣", "感情", "见面")

    data class Line(val cat: String, val text: String)

    val ALL: List<Line> = listOf(
        // ---- 日常：最安全，几乎不会踩雷 ----
        Line("日常", "今天忙到几点"),
        Line("日常", "刚吃完饭，你吃了没"),
        Line("日常", "你那边天气咋样"),
        Line("日常", "平时几点睡"),
        Line("日常", "周末一般干嘛"),

        // ---- 工作：对方一提职业就能接 ----
        Line("工作", "你做什么工作的"),
        Line("工作", "上班累不累"),
        Line("工作", "你们那行最近忙吗"),
        Line("工作", "一天要上几个小时"),
        Line("工作", "通勤远不远"),

        // ---- 兴趣：话题寿命最长，能聊很多轮 ----
        Line("兴趣", "平时刷手机都看啥"),
        Line("兴趣", "喜欢看剧还是刷短视频"),
        Line("兴趣", "有没有一直想去的地方"),
        Line("兴趣", "会做饭吗"),
        Line("兴趣", "运动吗，跑步还是健身"),

        // ---- 感情：离"能不能聊下去"最近，但别连着问 ----
        Line("感情", "你喜欢什么样的"),
        Line("感情", "一个人待着舒服还是有伴"),
        Line("感情", "介意异地吗"),
        Line("感情", "你信网上认识的吗"),
        Line("感情", "谈过几段"),

        // ---- 见面：往前推一步用的，别在对方还没热起来时点 ----
        Line("见面", "周末有空吗"),
        Line("见面", "要不要一起喝杯东西"),
        Line("见面", "你吃辣吗"),
        Line("见面", "附近有什么好吃的"),
        Line("见面", "哪天方便，我请你吃饭"),
    )

    fun of(cat: String): List<Line> = ALL.filter { it.cat == cat }
}
