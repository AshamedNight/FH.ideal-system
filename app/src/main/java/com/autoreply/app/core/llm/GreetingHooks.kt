package com.autoreply.app.core.llm

/**
 * 开场白钩子库：模板 + 槽位，以及"取一条"的规则。
 *
 * ## 为什么不是一堆固定的整句
 *
 * 对方先发了招呼，我方的第一句决定他会不会继续。固定的整句子有两个毛病：
 *   1. 重复。同一句发给二十个人，平台能查、人也能感觉到。
 *   2. 空。它不包含任何"这个人是具体某个人"的信息 —— 而人判断一句话是
 *      群发还是专门写给他，靠的就是这一点。
 *
 * 但聊天页能读到的信息就只有三样：**对方昵称、对方刚说的那句话、当前时段**
 * （距离、签名、照片都在资料页，要点进去才看得到，不值得为一句招呼多一次点击）。
 * 所以这里做的不是"个性化"，是**把这三样塞进句子里**：
 *
 *   「这么晚了还没睡，在刷什么」        ← 纯模板
 *   「{昵称}，这名字谁给你起的」        ← 有昵称，观感立刻不同
 *   「{原话}，就这么一句啊」            ← 引用了对方说的原话
 *
 * ## 槽位填不上就不发这条
 *
 * 这一条比看起来重要。昵称读不到时（`profiles.json` 没配 peerName、或者
 * 那个平台压根不暴露标题），如果照直替换，发出去的就是字面上的
 * 「{昵称}，这名字谁给你起的」—— 一次就够毁掉这个号。
 * 所以 [fill] 填不满就返回 null，调用方换下一条。
 */
object GreetingHooks {

    const val SLOT_NAME = "{昵称}"
    const val SLOT_ECHO = "{原话}"
    const val SLOT_TIME = "{时段}"

    /**
     * 内置库。**一条 = 一条要发出去的消息**，不再拼接成两三句连发。
     *
     * 分五类，混着用：
     *   - 反问：把球踢回去，最容易激起回复（人很难忍住不解释自己）
     *   - 自曝：先说一句自己的状态再问，比上来就查户口像人
     *   - 立门槛：略微"挑"，降低客服感 —— 一个什么都答应的号最像机器
     *   - 给信息：说个具体的地点/作息/天气，证明这是本地活人
     *   - 借话：引用对方刚说的那句话或昵称
     *
     * 写新的往这类推：**具体、不奉承、留一个能接的话头**。
     * "你好漂亮""在吗"这类不占钩子库的坑位 —— 它们不产生信息。
     *
     * D 组里的「张店」「淄博」是人设所在地，换城市要一起改。
     */
    val DEFAULT: List<String> = listOf(
        // ---- 反问 ----
        "这么晚了还没睡，在刷什么",
        "你先说，你是认真的还是群发的",
        "打招呼都这么客气，平时也这样吗",
        "头像是你在哪儿拍的",
        // ---- 自曝一点再问 ----
        "刚忙完，累得不想动。你忙不忙",
        "做手工做到现在，你有上瘾的事没",
        "我这人睡得晚，{时段}才有精神",
        "本来准备睡了，看到你这条",
        // ---- 立个小门槛 ----
        "先说好，我不太会主动，得你带",
        "我回消息慢，你别嫌",
        "能接受话少的人吗，先说清楚",
        "你话多还是话少，我这个比较挑",
        // ---- 给具体信息 ----
        "我张店这边，你离得远不远",
        "白天做副业规划，晚上才闲。你呢",
        "淄博这两天降温了，你那边冷不冷",
        "我不太爱出门，周末基本在家",
        // ---- 借对方的话 ----
        "{原话}，就这么一句啊",
        "{原话}，行，那我认真回你",
        "{昵称}，这名字谁给你起的",
        "{昵称}，看着像真名",
    )

    /**
     * 填槽。**任何一个槽位填不上就返回 null**（调用方换下一条），
     * 绝不把 `{昵称}` 这种字面量发出去。
     *
     * @param echo 对方刚说的那句话。超过 12 字不引用 —— 引用一整段会变成
     *   「你昨天说你想找个能聊得来的人，就这么一句啊」，读起来像复读机。
     */
    fun fill(line: String, name: String, echo: String, timeWord: String): String? {
        var s = line

        if (SLOT_NAME in s) {
            val n = name.trim()
            // 纯数字/超长的"昵称"是系统号（用户8823、游客12345678），
            // 引用它反而暴露这是脚本 —— 那种情况当作没读到。
            if (n.isEmpty() || n.length > 12 || n.all { it.isDigit() }) return null
            s = s.replace(SLOT_NAME, n)
        }

        if (SLOT_ECHO in s) {
            val e = echo.trim()
            if (e.isEmpty() || e.length > 12) return null
            s = s.replace(SLOT_ECHO, e)
        }

        if (SLOT_TIME in s) {
            if (timeWord.isBlank()) return null
            s = s.replace(SLOT_TIME, timeWord)
        }

        return s.trim().ifEmpty { null }
    }
}
